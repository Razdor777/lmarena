#!/usr/bin/env python3
"""
Пересобрать 26.62/src/Utils/Resources.hpp и Resources.cpp из 26.62/resources/.

CMake делает это сам на каждый configure (см. блок «Prepare the content for
Resources.hpp» в 26.62/CMakeLists.txt), но файлы лежат в репозитории, и без
переконфигурации они остаются старыми. Скрипт повторяет ту же логику:

  * имя ресурса  = путь с заменой '/', '.', '-' на '_'  (fonts/mntsb.ttf -> fonts_mntsb_ttf)
  * friendly name = имя файла без расширения, в нижнем регистре (mntsb)
  * для .ttf дополнительно FontHelper::Fonts.emplace(friendly, ...20px) и ..._large (42px)

Usage:
    python3 tools/gen_resources.py            # перезаписать файлы
    python3 tools/gen_resources.py --check    # только проверить, что актуально
"""

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJ = os.path.join(ROOT, '26.62')
RES = os.path.join(PROJ, 'resources')
OUT_HPP = os.path.join(PROJ, 'src', 'Utils', 'Resources.hpp')
OUT_CPP = os.path.join(PROJ, 'src', 'Utils', 'Resources.cpp')


def res_name(rel):
    return rel.replace('/', '_').replace('.', '_').replace('-', '_')


def friendly(rel):
    stem = os.path.splitext(os.path.basename(rel))[0]
    return stem.replace('-', '_').lower()


def collect():
    files = []
    for dirpath, _, names in os.walk(RES):
        for n in sorted(names):
            full = os.path.join(dirpath, n)
            files.append(os.path.relpath(full, RES).replace(os.sep, '/'))
    return sorted(files)


def build(files):
    hpp = ['// This file is generated by CMake. Do not edit it manually.',
           '#pragma once',
           '#include <string>',
           '#include <unordered_map>',
           '#include "Resource.hpp"',
           '']
    for rel in files:
        hpp.append(f'LOAD_RESOURCE({res_name(rel)});')
    hpp += ['',
            'class ResourceLoader {',
            'public:',
            '    static inline std::unordered_map<std::string, Resource> Resources;',
            '    static void loadResources();',
            '};',
            '']

    cpp = ['// This file is generated by CMake. Do not edit it manually.',
           '#include "Resources.hpp"',
           '#include "FontHelper.hpp"',
           '',
           'void ResourceLoader::loadResources() {',
           '    ImFontConfig font_config;',
           '    font_config.FontBuilderFlags = ImGuiFreeTypeBuilderFlags_NoHinting;']
    for rel in files:
        rn = res_name(rel)
        cpp.append(f'    auto {rn} = GET_RESOURCE({rn});')
        cpp.append(f'    Resources.emplace("{friendly(rel)}", {rn});')
        if rel.lower().endswith('.ttf'):
            fn = friendly(rel)
            cpp.append(f'    FontHelper::Fonts.emplace("{fn}", ImGui::GetIO().Fonts->AddFontFromMemoryTTF({rn}.data2(), {rn}.size(), 20, &font_config));')
            cpp.append(f'    FontHelper::Fonts.emplace("{fn}_large", ImGui::GetIO().Fonts->AddFontFromMemoryTTF({rn}.data2(), {rn}.size(), 42, &font_config));')
    cpp += ['}', '']
    return '\n'.join(hpp), '\n'.join(cpp)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()

    files = collect()
    hpp, cpp = build(files)
    cur_hpp = open(OUT_HPP, encoding='utf-8').read() if os.path.exists(OUT_HPP) else ''
    cur_cpp = open(OUT_CPP, encoding='utf-8').read() if os.path.exists(OUT_CPP) else ''

    stale = (hpp != cur_hpp) or (cpp != cur_cpp)
    if a.check:
        print(f'ресурсов: {len(files)}; файлы {"УСТАРЕЛИ" if stale else "актуальны"}')
        return 1 if stale else 0

    open(OUT_HPP, 'w', encoding='utf-8', newline='\n').write(hpp)
    open(OUT_CPP, 'w', encoding='utf-8', newline='\n').write(cpp)
    print(f'ресурсов: {len(files)}; Resources.hpp/.cpp перезаписаны')
    return 0


if __name__ == '__main__':
    sys.exit(main())
