#pragma once

//
// Nurik — что это вообще такое
// ─────────────────────────────────────────────────────────────────────────────
// Это НЕ текстовый шрифт и НЕ набор мелких UI-иконок вроде Tenacity-Icons.
// Внутри 30 крупных пиктограмм, каждая размером почти в весь em-квадрат (1024 upm),
// нарисованных моно-линией. Имён глифов нет (post 3.0), в cmap замаплен 31 код,
// поэтому понять, где какая иконка, можно было только отрисовав их.
// Из 31 кода два пустых: '!' (0x21) и 'a' (0x61) — это заглушки без контуров.
// Глифы сидят на ASCII-кодах, поэтому если выбрать Nurik как обычный шрифт,
// текст превращается в картинки (буквы A-Z подменены иконками).
//
// Ниже — то, что удалось опознать (остальное — абстрактная графика: спирали,
// значки-«звёздочки», «клавиатура», «принтер», «свеча» и т.п.).
//
//   '@' 0x40 — перо/самолётик (диагональная полоса с наконечником)
//   'C' 0x43 — клавиатура (скруглённый прямоугольник с рядами клавиш и пробелом)
//   'D' 0x44 — шестерёнка/объектив (кольцо с маленькими кольцами по сторонам)
//   'E' 0x45 — воронка/фильтр (узкий стакан, расширяющийся к низу)
//   'I' 0x49 — крестик в кольце  (ошибка/закрыть)
//   'J' 0x4A — переключатель, рычажок СПРАВА  (включено)
//   'K' 0x4B — переключатель, рычажок СЛЕВА   (выключено)
//   'L' 0x4C — крупный крестик в кольце  (ошибка/закрыть)
//   'M' 0x4D — восклицательный знак в кольце (предупреждение)
//   'Q' 0x51 — растущие полоски/лесенка (сигнал, подключение)
//   'R' 0x52 — лупа (поиск)
//   'U' 0x55 — звезда-искра с блёстками (эффект, «новое», успех)
//   'V' 0x56 — знак вопроса в кольце (справка/инфо)
//   'X' 0x58 — стрелка вверх с базовой линией (рост, ускорение)
//
// Рисовать их можно только иконочным шрифтом (FontHelper::getIconFont()):
//
//     #include <Utils/NurikIcons.hpp>
//     ImFont* icons = FontHelper::getIconFont();
//     drawList->AddText(icons, 20.f, pos, color, NurikIcons::kToggleOn);
//
namespace NurikIcons
{
    inline constexpr const char* kSwitchOn    = "J"; // 0x4A — рычажок справа
    inline constexpr const char* kSwitchOff   = "K"; // 0x4B — рычажок слева
    inline constexpr const char* kAlert       = "M"; // 0x4D — «!» в кольце
    inline constexpr const char* kCross       = "I"; // 0x49 — «×» в кольце
    inline constexpr const char* kCrossLarge  = "L"; // 0x4C — крупный «×» в кольце
    inline constexpr const char* kSignal      = "Q"; // 0x51 — растущие полоски
    inline constexpr const char* kQuestion    = "V"; // 0x56 — «?» в кольце
    inline constexpr const char* kSpark       = "U"; // 0x55 — звезда с блёстками
    inline constexpr const char* kSearch      = "R"; // 0x52 — лупа
    inline constexpr const char* kGear        = "D"; // 0x44 — шестерёнка
    inline constexpr const char* kKeyboard    = "C"; // 0x43 — клавиатура
    inline constexpr const char* kFilter      = "E"; // 0x45 — воронка
    inline constexpr const char* kTrend       = "X"; // 0x58 — стрелка вверх с линией
    inline constexpr const char* kQuill       = "@"; // 0x40 — перо

    // Размер, под который загружен FontHelper::getIconFont(): глифы занимают
    // почти весь em, поэтому рисовать их нужно этим размером (или меньшим).
    inline constexpr float kGlyphSize = 20.f;
}
